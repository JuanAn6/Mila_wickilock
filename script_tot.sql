--per calcular els camps el primer cop;
DECLARE
    V_DIF        INT;
    V_INFO       INT;
    V_SEG        INT;
    V_PAIS       INT;
    V_PER_COMENT INT;
    V_PER_FETA   INT;
    CURSOR C_RUTES IS
    SELECT
        *
    FROM
        RUTES FOR UPDATE;
BEGIN
    FOR V_RUTA IN C_RUTES LOOP
        V_DIF := 0;
        V_SEG := 0;
        V_PAIS := 0;
        V_INFO := 0;
        V_PER_COMENT := 0;
        V_PER_FETA := 0;
        SELECT
            COUNT(*) INTO V_PER_COMENT
        FROM
            COMENTARIS
        WHERE
            RUTA = V_RUTA.ID;
        SELECT
            COUNT(*) INTO V_PER_FETA
        FROM
            COMENTARIS
        WHERE
            FETA = 'S'
            AND RUTA = V_RUTA.ID;
        SELECT
            SUM(COMENTARIS.V_INFO) INTO V_INFO
        FROM
            COMENTARIS
        WHERE
            RUTA = V_RUTA.ID;
        SELECT
            SUM(COMENTARIS.DIFICULTAT) INTO V_DIF
        FROM
            COMENTARIS
        WHERE
            RUTA = V_RUTA.ID;
        SELECT
            SUM(COMENTARIS.V_SEGUIMENT) INTO V_SEG
        FROM
            COMENTARIS
        WHERE
            RUTA = V_RUTA.ID;
        SELECT
            SUM(COMENTARIS.V_PAISSATGE) INTO V_PAIS
        FROM
            COMENTARIS
        WHERE
            RUTA = V_RUTA.ID;
        UPDATE RUTES
        SET
            S_DIF = V_DIF,
            S_INFO = V_INFO,
            S_SEG = V_SEG,
            S_PAIS = V_PAIS,
            N_PER_COMENT = V_PER_COMENT,
            N_PER_FETA = V_PER_FETA
        WHERE
            CURRENT OF C_RUTES;
    END LOOP;
END;