DROP TABLE USUARIS CASCADE CONSTRAINTS;

CREATE TABLE USUARIS(
    LOGIN VARCHAR(30) CONSTRAINT LOGIN_PK PRIMARY KEY,
    EMAIL VARCHAR(40) CONSTRAINT NN_EMAIL NOT NULL CONSTRAINT SK_MAIL UNIQUE,
    PWD VARCHAR(40) CONSTRAINT NN_PWD NOT NULL,
    FOTO BLOB
);

DROP TABLE RUTES CASCADE CONSTRAINTS;

CREATE TABLE RUTES(
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT RUTES_ID_PK PRIMARY KEY,
    PROPIETARI VARCHAR(30) CONSTRAINT NN_PROPIETARI NOT NULL CONSTRAINT FK_PROPIETARI REFERENCES USUARIS,
    TITOL VARCHAR(40) CONSTRAINT NN_TITOL NOT NULL,
    DESCRIPCIO VARCHAR(200),
    TEXTHTML CLOB,
    DATA DATE CONSTRAINT NN_DATA NOT NULL,
    DISTANCIA FLOAT(6) CONSTRAINT NN_DISTANCIA NOT NULL,
    TEMPS NUMBER(10) CONSTRAINT NN_TEMPS NOT NULL, --esta en segons, restant dos timstamp;
    DESN_P NUMBER(4),
    DESN_N NUMBER(4),
    DIFICULTAT NUMBER(1),
    CONSTRAINT RUTES_DIFICULTAT_CHECK CHECK (DIFICULTAT >= 0 AND DIFICULTAT <= 5)
);

DROP TABLE TIPUS CASCADE CONSTRAINTS;

CREATE TABLE TIPUS(
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_TIPUS PRIMARY KEY,
    NOM VARCHAR(30) CONSTRAINT TIPUS_NN_NOM NOT NULL,
    ICONA BLOB
);

DROP TABLE PUNTS CASCADE CONSTRAINTS;

CREATE TABLE PUNTS(
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_PUNTS PRIMARY KEY,
    NUM NUMBER (4),
    RUTA NUMBER(4),
    NOM VARCHAR(30) CONSTRAINT PUNT_NN_NOM NOT NULL,
    DESCRIPCIO VARCHAR(200),
    LAT NUMBER(6, 2) CONSTRAINT PUNT_NN_LAT NOT NULL,
    LON NUMBER(6, 2) CONSTRAINT PUTN_NN_LON NOT NULL,
    ALT NUMBER(4) CONSTRAINT PUNT_NN_ALT NOT NULL,
    TIPUS NUMBER(4),
    FOTO BLOB,
    CONSTRAINT PUNTS_FK_RUTA FOREIGN KEY (RUTA) REFERENCES RUTES,
    CONSTRAINT PUNTS_FK_TIPUS FOREIGN KEY (TIPUS) REFERENCES TIPUS
);

DROP TABLE COMENTARIS CASCADE CONSTRAINTS;

CREATE TABLE COMENTARIS(
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT COMENTARI_PK PRIMARY KEY,
    USUARI VARCHAR(30) CONSTRAINT USUARI_NN_COMENTARI NOT NULL,
    RUTA NUMBER(4) CONSTRAINT RUTA_NN_COMENTARI NOT NULL,
    TEXT VARCHAR(200) CONSTRAINT TEXT_NN_COMENTARI NOT NULL,
    DATA DATE CONSTRAINT NN_DATA_COMENTARI NOT NULL,
    V_INFO NUMBER(1),
    FETA CHAR(1),
    V_SEGUIMENT NUMBER(1),
    V_PAISSATGE NUMBER(1),
    DIFICULTAT NUMBER(1),
    CONSTRAINT COMENTARIS_FK_RUTA FOREIGN KEY (RUTA) REFERENCES RUTES,
    CONSTRAINT COMENTARIS_FK_USUARI FOREIGN KEY (USUARI) REFERENCES USUARIS,
    CONSTRAINT COMENTARIS_FETA_CHECK CHECK (FETA = 'S' OR FETA = 'N'),
    CONSTRAINT COMENTARIS_V_INFO_CHECK CHECK (V_INFO <= 5 AND V_INFO >= 0)
 --aquestes restrigsions s'han de fer en un trigger;
