 --constraint comentaris_dificultat_check check (dificultat <= 5 and dificultat >= 0),
 --constraint comentaris_v_seguiment_check2 check (v_seguiment = null and feta = 'N'),
 --constraint comentaris_v_paissatge_check2 check (v_paissatge = null and feta = 'N'),
 --constraint comentaris_dificultat_check2 check (dificultat = null and feta = 'N')
);

DROP TABLE COMPANYS CASCADE CONSTRAINTS;

CREATE TABLE COMPANYS(
    COMENTARI NUMBER(4),
    USUARI VARCHAR(30),
    CONSTRAINT COMAPNYS_PK PRIMARY KEY (COMENTARI, USUARI),
    CONSTRAINT COMANYS_FK_COMENTARI FOREIGN KEY (COMENTARI) REFERENCES COMENTARIS,
    CONSTRAINT COMPANYS_FK_USUARI FOREIGN KEY (USUARI) REFERENCES USUARIS
);

DROP TABLE FETES CASCADE CONSTRAINTS;

CREATE TABLE FETES(
    RUTA NUMBER(4) CONSTRAINT FETES_NN_RUTA NOT NULL,
    USUARI VARCHAR(30),
    DATA DATE,
    CONSTRAINT FETES_PK PRIMARY KEY (USUARI, DATA),
    CONSTRAINT FETES_FK_USUARI FOREIGN KEY (USUARI) REFERENCES USUARIS,
    CONSTRAINT FETES_FK_RUTA FOREIGN KEY (RUTA) REFERENCES RUTES
);

